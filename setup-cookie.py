"""Log in to Rawpixel in a browser window and save the session cookie to .env.

    uv run setup-cookie.py
"""
import re
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

ENV_PATH = Path(__file__).resolve().parent / ".env"


def main() -> int:
    print("=== Rawpixel Session Cookie Setup ===\n")
    print("This will open a browser, let you log in, then save your session cookie to .env\n")
    if input("Ready to continue? (y/n): ").strip().lower() != "y":
        print("Setup cancelled.")
        return 0

    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=False)
        context = browser.new_context()
        page = context.new_page()
        page.goto("https://www.rawpixel.com/user/login")
        print("\nLog in to Rawpixel in the browser window.")
        input("Press Enter after you've logged in: ")

        cookie = next((c for c in context.cookies() if c["name"].startswith("SSESS")), None)
        browser.close()

    if not cookie:
        print("\n❌ Could not find session cookie (SSESS...). Make sure you're logged in and try again.")
        return 1

    line = f"RAWPIXEL_SESSION_COOKIE={cookie['name']}={cookie['value']}"
    if ENV_PATH.exists():
        text = ENV_PATH.read_text(encoding="utf-8")
        if "RAWPIXEL_SESSION_COOKIE=" in text:
            text = re.sub(r"^RAWPIXEL_SESSION_COOKIE=.*$", lambda _: line, text, flags=re.M)
        else:
            text += f"\n{line}\n"
    else:
        text = f"# Rawpixel Session Cookie (generated by setup-cookie.py)\n\n{line}\n"
    ENV_PATH.write_text(text, encoding="utf-8")
    print("\n✅ Session cookie saved to .env\nNow run: uv run rp-downloader.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
